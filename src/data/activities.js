/**
 * Search activities by name
 * @param {string} query - Search query
 * @param {string} type - Activity type ('fitness', 'cooking', 'games')
 * @returns {Array} Matching activities
 */
export function searchActivities(query, type = 'all') {
  const lowerQuery = query.toLowerCase();
  let results = [];

  if (type === 'all' || type === 'fitness') {
    results = results.concat(
      FITNESS_ACTIVITIES.filter((activity) => activity.name.toLowerCase().includes(lowerQuery))
    );
  }

  if (type === 'all' || type === 'cooking') {
    results = results.concat(
      COOKING_ACTIVITIES.filter((activity) => activity.name.toLowerCase().includes(lowerQuery))
    );
  }

  if (type === 'all' || type === 'games') {
    results = results.concat(
      GAMES_LIBRARY.filter((game) => game.name.toLowerCase().includes(lowerQuery))
    );
  }

  return results;
}
